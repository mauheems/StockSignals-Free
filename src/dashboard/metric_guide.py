def _m(name: str, category: str, what: str, read: str, calc: str, source: str, caveat: str | None = None, score: str | None = None) -> dict:
    entry = {"name": name, "category": category, "what": what, "read": read, "calc": calc, "source": source}
    if caveat:
        entry["caveat"] = caveat
    if score:
        entry["score"] = score
    return entry


